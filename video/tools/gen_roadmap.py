"""Generate video/ROADMAP.md: one row per handbook topic, with its video status.

Topics come from the chapter tables in docs/*/README.md (rows whose chapter cell is a
link; Planned rows are plain text and are skipped). Status comes from two places:

  planned   no script yet
  scripted  video/scripts/<part>/<name>.md exists
  rendered  recorded in video/status.json (video made, not uploaded yet)
  published recorded in video/status.json with an https YouTube link

Edit video/status.json, never ROADMAP.md. Usage:
  python3 video/tools/gen_roadmap.py           # write video/ROADMAP.md
  python3 video/tools/gen_roadmap.py --check   # exit 1 if ROADMAP.md is stale or status.json is invalid
"""
from __future__ import annotations

import json
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
STATUSES = ("planned", "scripted", "rendered", "published")
LABELS = {
    "planned": "⬜ Planned",
    "scripted": "✍️ Scripted",
    "rendered": "🎬 Rendered",
    "published": "✅ Published",
}
_ROW = re.compile(r"^\|\s*(\d+)\s*\|\s*\[([^\]]+)\]\(([^)#]+)(?:#[^)]*)?\)")


@dataclass(frozen=True)
class Topic:
    part_slug: str
    part_title: str
    number: int
    title: str
    path: str  # repo-relative, posix
    script: str  # repo-relative, posix


def collect_topics(root: Path) -> list[Topic]:
    topics: list[Topic] = []
    for readme in sorted((root / "docs").glob("*/README.md")):
        slug = readme.parent.name
        if not re.match(r"^\d\d-", slug):
            continue
        lines = readme.read_text(encoding="utf-8").splitlines()
        h1 = next((ln[2:].strip() for ln in lines if ln.startswith("# ")), slug)
        rel_dir = readme.parent.relative_to(root)
        for line in lines:
            match = _ROW.match(line)
            if not match:
                continue
            number, title, target = int(match.group(1)), match.group(2).strip(), match.group(3).strip()
            path = Path(os.path.normpath(os.path.join(rel_dir, target))).as_posix()
            name = Path(path).parent.name if path.endswith("/README.md") else Path(path).stem
            topics.append(Topic(slug, h1, number, title, path, f"video/scripts/{slug}/{name}.md"))
    return topics


def load_status(root: Path) -> dict:
    file = root / "video" / "status.json"
    data = json.loads(file.read_text(encoding="utf-8")) if file.is_file() else {}
    data.setdefault("videos", {})
    data.setdefault("pilots", [])
    return data


def derive_status(topic: Topic, videos: dict, root: Path) -> str:
    record = videos.get(topic.path)
    if record and record.get("status") == "published":
        return "published"
    if record and record.get("status") == "rendered":
        return "rendered"
    if (root / topic.script).is_file():
        return "scripted"
    return "planned"


def validate_status(status: dict, topics: list[Topic], root: Path) -> list[str]:
    errors: list[str] = []
    by_path = {t.path: t for t in topics}
    for path, record in status["videos"].items():
        if path not in by_path:
            errors.append(f"status.json: '{path}' is not a topic in any part README")
            continue
        value = record.get("status")
        if value not in ("rendered", "published"):
            errors.append(f"status.json: '{path}' status '{value}' must be 'rendered' or 'published'")
            continue
        if not (root / by_path[path].script).is_file():
            errors.append(f"status.json: '{path}' is {value} but its script {by_path[path].script} is missing")
        if value == "published" and not str(record.get("youtube") or "").startswith("https://"):
            errors.append(f"status.json: '{path}' is published, so 'youtube' must be an https URL")
    for path in status["pilots"]:
        if path not in by_path:
            errors.append(f"status.json: pilot '{path}' is not a topic in any part README")
    return errors


def render_roadmap(root: Path) -> str:
    topics = collect_topics(root)
    status = load_status(root)
    videos, pilots = status["videos"], set(status["pilots"])
    state = {t.path: derive_status(t, videos, root) for t in topics}
    total = len(topics)
    published = sum(1 for v in state.values() if v == "published")
    by_path = {t.path: t for t in topics}
    next_pilot = next(
        (by_path[p] for p in status["pilots"] if p in by_path and state[p] == "planned"), None
    )
    next_topic = next_pilot or next((t for t in topics if state[t.path] == "planned"), None)

    out = [
        "<!-- Generated by video/tools/gen_roadmap.py from docs/*/README.md and video/status.json. "
        "Edit status.json, not this file. -->",
        "",
        "# Video roadmap",
        "",
        "One video per handbook topic, 5–10 minutes each. This page tracks which topics have a video.",
        "",
        f"**{published} of {total}** topics published.",
        "",
        "## How videos are made and tracked",
        "",
        "- Each video is made with the concept-explainer skill and the pipeline in this folder "
        "(script, validate, render; see [README.md](README.md)), following the "
        "[design spec](specs/2026-11-10-video-series-design.md).",
        "- Finished videos are not committed (about 20 MB each). Upload to YouTube, then record the link.",
        "- To update this page: edit `video/status.json` (set a topic to `rendered`, or to `published` with its "
        "`youtube` link), then run `python3 video/tools/gen_roadmap.py`.",
        "- Status ladder: ⬜ Planned (no script) → ✍️ Scripted (script exists) → 🎬 Rendered (video made, "
        "not uploaded) → ✅ Published (YouTube link recorded). ⭐ marks a pilot video.",
        "",
    ]
    if next_topic:
        out += [
            f"Next up: **{next_topic.title}** "
            f"({'pilot, ' if next_pilot else ''}{next_topic.part_title}, topic {next_topic.number})",
            "",
        ]
    out += [
        "## Progress by part",
        "",
        "| Part | Published | Rendered | Scripted | Planned | Total |",
        "|---|---|---|---|---|---|",
    ]
    parts: dict[str, list[Topic]] = {}
    for t in topics:
        parts.setdefault(t.part_slug, []).append(t)
    for items in parts.values():
        count = {s: sum(1 for t in items if state[t.path] == s) for s in STATUSES}
        out.append(
            f"| {items[0].part_title} | {count['published']} | {count['rendered']} | "
            f"{count['scripted']} | {count['planned']} | {len(items)} |"
        )
    for items in parts.values():
        out += ["", f"## {items[0].part_title}", "", "| # | Topic | Status | Video |", "|---|---|---|---|"]
        for t in items:
            star = " ⭐" if t.path in pilots else ""
            record = videos.get(t.path, {})
            link = f"[Watch]({record['youtube']})" if state[t.path] == "published" else "—"
            out.append(f"| {t.number} | [{t.title}](../{t.path}){star} | {LABELS[state[t.path]]} | {link} |")
    return "\n".join(out) + "\n"


def run(root: Path, check: bool) -> int:
    topics = collect_topics(root)
    errors = validate_status(load_status(root), topics, root)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    text = render_roadmap(root)
    target = root / "video" / "ROADMAP.md"
    if check:
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            print("video/ROADMAP.md is stale: run python3 video/tools/gen_roadmap.py", file=sys.stderr)
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(run(REPO_ROOT, check="--check" in sys.argv[1:]))
